    case chinese = "zh-CN"
    case english = "en"

    public init(from decoder: Decoder) throws {
        let raw = try decoder.singleValueContainer().decode(String.self)
        self = AppLanguage(rawValue: raw) ?? .chinese
    }

    public func text(_ key: String, _ arguments: CVarArg...) -> String {
        format(key, arguments: arguments)
    }

    public func format(_ key: String, arguments: [CVarArg]) -> String {
        let template = self == .english ? Self.englishText[key] ?? key : key
        return arguments.isEmpty ? template : String(format: template, locale: Locale(identifier: rawValue), arguments: arguments)
    }

